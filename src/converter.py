def mxn_to_usd(mxn):
        tipo_cambio = 18.5
        return round(mxn/tipo_cambio, 2)
def usd_to_mxn(usd):
        tipo_cambio = 18.5
        return round(usd*tipo_cambio, 2)
def mxn_to_eur(mxn):
        tipo_cambio = 21.30
        return round(mxn*tipo_cambio, 2)
def eur_to_mxn(eur):
        tipo_cambio = 21
        return round(eur/tipo_cambio, 2)
def usd_to_eur(usd):
        tipo_cambio = 0.92
        return round(usd*tipo_cambio, 2)